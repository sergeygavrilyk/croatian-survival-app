/**
 * Відтворюване «випадкове» перемішування (чиста логіка — тестується в random.test.ts).
 *
 * Навіщо (баг 2026-10-20, помилка React #418 на «Мої помилки» і «Типові помилки»): клієнтський компонент
 * рендериться спершу на сервері, потім у браузері. Math.random під час рендеру дає різний порядок плиток
 * і варіантів — React бачить, що текст не збігається, і перебудовує екран. Тепер сервер передає сторінці
 * випадковий seed, і обидва рендери перемішують однаково (а кожне відкриття сторінки — по-новому).
 */

/** Генератор чисел 0…1 з рядка-seed (хеш xmur3 + mulberry32): однаковий seed → однакова послідовність. */
export function seededRandom(seed: string): () => number {
  let h = 1779033703 ^ seed.length;
  for (let i = 0; i < seed.length; i++) {
    h = Math.imul(h ^ seed.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  let a = (h ^ (h >>> 16)) >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Новий seed для сторінки (сервер): передається в клієнтський компонент як prop. */
export function newSeed(): string {
  return Math.random().toString(36).slice(2, 10);
}
