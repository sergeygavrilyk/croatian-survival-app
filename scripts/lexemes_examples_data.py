def _parse(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.strip().split('\n'):
        if not line.strip():
            continue
        key, sentence = line.split(' :: ', 1)
        key = key.strip().lower()
        if key in out:
            raise SystemExit(f'Повтор леми в прикладах: {key}')
        out[key] = sentence.strip()
    return out


