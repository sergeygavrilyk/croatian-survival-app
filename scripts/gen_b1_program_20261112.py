        assess = max(12, min(20, 2 * len(ls)))
        tot_as += assess
        word = 'уроки' if len(ls) in (2, 3, 4) else 'уроків'
        out.append(f'### B1.{i} — {ua} (*{hr}*) · {len(ls)} {word} · ≈ {w} одиниць (≈ {w - COLLOC * len(ls)} слів + {COLLOC * len(ls)} словосполучень)\n')
